def main():
    parser = argparse.ArgumentParser(
        description='Generate G3DT geotechnical report in LaTeX format',
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Examples:
    python generate_latex.py --sample --output report.tex
    python generate_latex.py --sample --compile
    python generate_latex.py --sample --compile --output-dir /tmp/reports
        """
    )
    parser.add_argument('--output', '-o', default='generated-report.tex',
                        help='Output .tex file path (default: generated-report.tex)')
    parser.add_argument('--sample', action='store_true',
                        help='Use sample data from 3001631 (Rubí)')
    parser.add_argument('--compile', '-c', action='store_true',
                        help='Also compile to PDF using xelatex')
    parser.add_argument('--output-dir', '-d',
                        help='Output directory for compiled PDF')
    parser.add_argument('--copy-to',
                        help='Copy generated PDF to this location')

    args = parser.parse_args()

    # Use sample data
    if args.sample:
        data = SAMPLE_DATA_RUBI
    else:
        data = SAMPLE_DATA_RUBI
        print("Using sample data. Implement JSON/YAML input for production use.")

    # Generate LaTeX
    generator = G3DTLatexGenerator()
    tex_path = Path(args.output)

    # Ensure output is in the same directory as the script (for assets)
    if not tex_path.is_absolute():
        tex_path = Path(__file__).parent / tex_path

    generator.generate(data, tex_path)

    # Compile if requested
    if args.compile:
        output_dir = Path(args.output_dir) if args.output_dir else tex_path.parent
        pdf_path = generator.compile(tex_path, output_dir)

        # Copy if requested
        if pdf_path and args.copy_to:
            dest = Path(args.copy_to)
            shutil.copy(pdf_path, dest)
            print(f"PDF copied to: {dest}")


if __name__ == '__main__':
    main()
