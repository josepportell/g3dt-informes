    def generate_annexes(self) -> List[str]:
        """Generate annex placeholders."""
        annexes = [
            ("ANNEX 1", "Base de càlcul"),
            ("ANNEX 2", "Registre d'assaigs mecànics"),
            ("ANNEX 3", "Esquema situació assaigs"),
            ("ANNEX 4", "Tall de correlació"),
            ("ANNEX 5", "Fotografies"),
            ("ANNEX 6", "Actes d'assaig de laboratori"),
        ]

        lines = [
            r"% ============================================================================",
            r"% ANNEXES",
            r"% ============================================================================",
            r"",
            r"\appendix",
            r"",
            r"\section*{ANNEXES}",
            r"\addcontentsline{toc}{section}{ANNEXES}",
            r"",
        ]

        for num, title in annexes:
            lines.append(f"\\subsection*{{{num}: {escape_latex(title)}}}")
            lines.append(f"\\addcontentsline{{toc}}{{subsection}}{{{num}: {escape_latex(title)}}}")
            lines.append(f"[Contingut de l'{num.lower()}]")
            lines.append(r"")

        return lines

    def generate(self, data: Dict, output_path: Path) -> Path:
        """Generate complete LaTeX document."""
        self.content = []

        # Build document
        self.add_lines(self.generate_preamble())
        self.add_lines(self.generate_cover(data))
        self.add_lines(self.generate_toc())
        self.add_lines(self.generate_section_1(data))
        self.add_lines(self.generate_section_2(data))
        self.add_lines(self.generate_section_3(data))
        self.add_lines(self.generate_section_4(data))
        self.add_lines(self.generate_signature(data))
        self.add_lines(self.generate_annexes())

        # End document
        self.add_line(r"\end{document}")

        # Write to file
        output_path = Path(output_path)
        with open(output_path, 'w', encoding='utf-8') as f:
            f.write('\n'.join(self.content))

        print(f"LaTeX file generated: {output_path}")
        return output_path

    def compile(self, tex_path: Path, output_dir: Path = None) -> Path:
        """Compile LaTeX to PDF using xelatex."""
        tex_path = Path(tex_path)
        output_dir = Path(output_dir) if output_dir else tex_path.parent

        # Run xelatex twice (for cross-references)
        for i in range(2):
            cmd = [
                'xelatex',
                '-interaction=nonstopmode',
                f'-output-directory={output_dir}',
                str(tex_path)
            ]

            print(f"Running xelatex (pass {i+1}/2)...")
            result = subprocess.run(
                cmd,
                cwd=tex_path.parent,
                capture_output=True,
                text=True
            )

            if result.returncode != 0:
                print(f"Warning: xelatex returned {result.returncode}")
                # Print last 20 lines of output for debugging
                lines = result.stdout.split('\n')[-20:]
                print('\n'.join(lines))

        pdf_path = output_dir / tex_path.with_suffix('.pdf').name
        if pdf_path.exists():
            print(f"PDF generated: {pdf_path}")
            return pdf_path
        else:
            print("Warning: PDF not found after compilation")
            return None


