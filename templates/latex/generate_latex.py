def escape_latex(text: str) -> str:
    """Escape special LaTeX characters."""
    if text is None:
        return ""

    # Characters that need escaping in LaTeX
    replacements = [
        ('\\', r'\textbackslash{}'),
        ('&', r'\&'),
        ('%', r'\%'),
        ('$', r'\$'),
        ('#', r'\#'),
        ('_', r'\_'),
        ('{', r'\{'),
        ('}', r'\}'),
        ('~', r'\textasciitilde{}'),
        ('^', r'\textasciicircum{}'),
    ]

    for char, escaped in replacements:
        text = text.replace(char, escaped)

    # Handle line breaks
    text = text.replace('\n', r'\\')

    return text


def format_table_row(cells: List[str], header: bool = False) -> str:
    """Format a table row in LaTeX."""
    escaped = [escape_latex(str(c)) for c in cells]
    if header:
        escaped = [f"\\tableheader{{{c}}}" for c in escaped]
    return " & ".join(escaped) + r" \\"


class G3DTLatexGenerator:
    """Generate G3DT geotechnical reports in LaTeX format."""

    def __init__(self, template_dir: Path = None):
        self.template_dir = template_dir or Path(__file__).parent
        self.content = []

    def add_line(self, line: str = ""):
        """Add a line to the document."""
        self.content.append(line)

    def add_lines(self, lines: List[str]):
        """Add multiple lines."""
        self.content.extend(lines)

    def generate_preamble(self) -> List[str]:
        """Generate document preamble."""
        return [
            r"% G3DT Geotechnical Report",
            r"% Auto-generated by generate_latex.py",
            r"% Compile with: xelatex <filename>.tex",
            r"",
            r"\documentclass{g3dt-report}",
            r"",
            r"\begin{document}",
            r"",
        ]

    def generate_cover(self, data: Dict) -> List[str]:
        """Generate cover page."""
        client = escape_latex(data.get('client', '------'))
        expedient = escape_latex(data.get('expedient', ''))
        date = escape_latex(data.get('data', ''))
        obra = data.get('obra', '').replace('\n', r'\\' + '\n     ')
        obra = escape_latex(obra).replace(r'\\\\', r'\\')  # Handle double escaping
        location = data.get('obra', '').split('\n')[-1].split('(')[0].strip() if data.get('obra') else 'LOCALITAT'
        location = escape_latex(location)

        return [
            r"% ============================================================================",
            r"% COVER PAGE",
            r"% ============================================================================",
            r"",
            r"\makecover",
            f"    {{{client}}}",
            f"    {{{expedient}}}",
            f"    {{{date}}}",
            f"    {{{obra}}}",
            f"    {{{location}}}",
            r"",
        ]

    def generate_toc(self) -> List[str]:
        """Generate table of contents."""
        return [
            r"% ============================================================================",
            r"% TABLE OF CONTENTS",
            r"% ============================================================================",
            r"",
            r"\tableofcontents",
            r"\newpage",
            r"",
        ]

